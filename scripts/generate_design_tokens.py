"""Generate ui/theme/SteplyTokens.kt from design/figma/tokens.json.

From the repo root:

  python scripts/generate_design_tokens.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "figma" / "tokens.json"
OUTPUT = ROOT / "app" / "src" / "main" / "java" / "io" / "github" / "enterenn" / "steply" / "ui" / "theme" / "SteplyTokens.kt"

HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
ROLES = ("display", "title", "body", "caption")
FONT_FAMILY = {"ui": "SteplyUiFont", "figures": "SteplyFiguresFont"}
WEIGHTS = set(range(300, 901, 100))


def fail(message: str) -> None:
    raise SystemExit(message)


def load() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        fail("tokens.json must be an object")
    return data


def hex_color(value: object, label: str) -> str:
    if not isinstance(value, str) or HEX.fullmatch(value) is None:
        fail(f"{label} must be a #RRGGBB hex")
    return f"Color(0xFF{value[1:].upper()})"


def pair(value: object, label: str) -> tuple[str, str]:
    if not isinstance(value, dict):
        fail(f"{label} must be an object with light and dark")
    return hex_color(value.get("light"), f"{label}.light"), hex_color(value.get("dark"), f"{label}.dark")


def column(value: object, label: str) -> str:
    if value not in ("light", "dark"):
        fail(f"{label} must be \"light\" or \"dark\"")
    return value


def number(value: object, label: str) -> str:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(f"{label} must be a number")
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def enum_name(key: str) -> str:
    return key[0].upper() + key[1:]


def font_weight(value: object, label: str) -> str:
    if isinstance(value, bool) or not isinstance(value, int) or value not in WEIGHTS:
        fail(f"{label} must be a weight from 300 to 900 in steps of 100")
    return f"FontWeight.W{value}"


def role_color(column_name: str) -> str:
    return "preset.dark" if column_name == "dark" else "preset.light"


def build(data: dict) -> str:
    colors = data.get("color")
    if not isinstance(colors, dict) or "accent" not in colors:
        fail("color.accent is required")

    lines = [
        "// Generated by scripts/generate_design_tokens.py from design/figma/tokens.json.",
        "// Do not edit by hand.",
        "package io.github.enterenn.steply.ui.theme",
        "",
        "import androidx.compose.runtime.Immutable",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.TextStyle",
        "import androidx.compose.ui.text.font.FontFamily",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.Dp",
        "import androidx.compose.ui.unit.TextUnit",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "internal object SteplyTokens {",
    ]

    for key, value in colors.items():
        if key == "accent":
            continue
        light, dark = pair(value, f"color.{key}")
        lines.append(f"    val {key}Light = {light}")
        lines.append(f"    val {key}Dark = {dark}")

    accents = colors["accent"]
    if not isinstance(accents, dict) or not accents:
        fail("color.accent must contain the accent presets")
    for key, value in accents.items():
        light, dark = pair(value, f"color.accent.{key}")
        name = enum_name(key)
        lines.append(f"    val accent{name}Light = {light}")
        lines.append(f"    val accent{name}Dark = {dark}")
    lines.append("}")
    lines.append("")

    lines.append("enum class AccentPreset(val light: Color, val dark: Color) {")
    entries = []
    for key in accents:
        name = enum_name(key)
        entries.append(f"    {name}(SteplyTokens.accent{name}Light, SteplyTokens.accent{name}Dark),")
    entries[-1] = entries[-1].rstrip(",")
    lines.extend(entries)
    lines.append("}")
    lines.append("")

    roles = data.get("accentRoles")
    if not isinstance(roles, dict):
        fail("accentRoles is required")
    for function, role_name in (("accentColor", "accent"), ("accentFillColor", "accentFill")):
        role = roles.get(role_name)
        if not isinstance(role, dict):
            fail(f"accentRoles.{role_name} is required")
        light = role_color(column(role.get("light"), f"accentRoles.{role_name}.light"))
        dark = role_color(column(role.get("dark"), f"accentRoles.{role_name}.dark"))
        lines.append(f"internal fun {function}(preset: AccentPreset, dark: Boolean): Color =")
        lines.append(f"    if (dark) {dark} else {light}")
        lines.append("")

    scale = data.get("typography", {}).get("scale") if isinstance(data.get("typography"), dict) else None
    if not isinstance(scale, dict):
        fail("typography.scale is required")
    missing = [role for role in ROLES if role not in scale]
    if missing:
        fail("typography.scale is missing " + ", ".join(missing))

    style_lines = []
    for role in ROLES:
        spec = scale[role]
        if not isinstance(spec, dict):
            fail(f"typography.scale.{role} must be an object")
        font = spec.get("font")
        if font not in FONT_FAMILY:
            fail(f"typography.scale.{role}.font must be ui or figures")
        size = number(spec.get("size"), f"typography.scale.{role}.size")
        line_height = number(spec.get("lineHeight"), f"typography.scale.{role}.lineHeight")
        weight = font_weight(spec.get("weight"), f"typography.scale.{role}.weight")
        family = FONT_FAMILY[font]
        style_lines.append(f"    {role} = textStyle({family}, {size}.sp, {line_height}.sp, {weight}),")

    lines.append("@Immutable")
    lines.append("data class SteplyTypography(")
    lines.append("    val ui: FontFamily,")
    lines.append("    val figures: FontFamily,")
    lines.append("    val display: TextStyle,")
    lines.append("    val title: TextStyle,")
    lines.append("    val body: TextStyle,")
    lines.append("    val caption: TextStyle,")
    lines.append(")")
    lines.append("")
    lines.append("private fun textStyle(font: FontFamily, size: TextUnit, lineHeight: TextUnit, weight: FontWeight) =")
    lines.append("    TextStyle(fontFamily = font, fontSize = size, lineHeight = lineHeight, fontWeight = weight)")
    lines.append("")
    lines.append("fun steplyTypography(): SteplyTypography = SteplyTypography(")
    lines.append("    ui = SteplyUiFont,")
    lines.append("    figures = SteplyFiguresFont,")
    style_lines[-1] = style_lines[-1].rstrip(",")
    lines.extend(style_lines)
    lines.append(")")
    lines.append("")

    lines.extend(metric_type("SteplySpacing", data.get("spacing"), "spacing", "dp"))
    lines.extend(metric_type("SteplyRadius", data.get("radius"), "radius", "dp"))
    return "\n".join(lines) + "\n"


def metric_type(type_name: str, value: object, label: str, unit: str) -> list[str]:
    if not isinstance(value, dict) or not value:
        fail(f"{label} must be a non-empty object")
    fields = []
    args = []
    for key, raw in value.items():
        if not key.isidentifier():
            fail(f"{label}.{key} is not a Kotlin identifier")
        amount = number(raw, f"{label}.{key}")
        fields.append(f"    val {key}: Dp,")
        args.append(f"    {key} = {amount}.{unit},")
    instance = type_name[0].lower() + type_name[1:]
    return [
        "@Immutable",
        f"data class {type_name}(",
        *fields,
        ")",
        "",
        f"internal val {instance} = {type_name}(",
        *args,
        ")",
        "",
    ]


def main() -> None:
    OUTPUT.write_text(build(load()), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
